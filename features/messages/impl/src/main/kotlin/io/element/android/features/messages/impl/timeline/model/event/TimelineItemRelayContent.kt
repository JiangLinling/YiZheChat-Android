package io.element.android.features.messages.impl.timeline.model.event

import kotlinx.collections.immutable.ImmutableList
import kotlinx.collections.immutable.toImmutableList
import kotlinx.collections.immutable.ImmutableSet
import kotlinx.collections.immutable.persistentSetOf
import kotlinx.collections.immutable.persistentListOf
import io.element.android.libraries.matrix.api.timeline.item.event.ProtectedRelayEntry
import org.jsoup.nodes.Document

data class TimelineItemRelayContent(
    override val body: String,
    val title: String,
    val entries: ImmutableList<String>,
    val closed: Boolean,
    override val isEdited: Boolean,
    val itemDetails: ImmutableList<ProtectedRelayEntry> = persistentListOf(),
    val editableItemIds: ImmutableSet<String> = persistentSetOf(),
) : TimelineItemTextBasedContent {
    override val htmlDocument: Document? = null
    override val formattedBody: CharSequence = body
    override val plainText: String = body
    override val type: String = "TimelineItemRelayContent"
}

private val RELAY_ENTRY_PATTERN = Regex("""^\s*\d+\.\s+(.+?)\s*$""")

/** Parses only the authenticated relay projection generated by the protected-content adapter. */
internal fun parseProtectedRelayBody(
    body: String,
    isEdited: Boolean,
    itemDetails: ImmutableList<ProtectedRelayEntry>? = null,
): TimelineItemRelayContent? {
    val lines = body.lines()
    val firstLine = lines.firstOrNull()?.trim().orEmpty()
    if (!firstLine.startsWith(RELAY_TITLE_PREFIX)) return null
    val title = firstLine.removePrefix(RELAY_TITLE_PREFIX).trim().takeIf(String::isNotEmpty) ?: return null
    val entries = lines.mapNotNull { line ->
        RELAY_ENTRY_PATTERN.matchEntire(line)?.groupValues?.getOrNull(1)?.trim()?.takeIf(String::isNotEmpty)
    }
    return TimelineItemRelayContent(
        body = body,
        title = title,
        entries = itemDetails?.map { it.text }?.toImmutableList() ?: entries.toImmutableList(),
        closed = lines.any { it.trim() == RELAY_CLOSED_MARKER },
        isEdited = isEdited,
        itemDetails = itemDetails ?: persistentListOf(),
    )
}

internal const val RELAY_TITLE_PREFIX = "接龙："
internal const val RELAY_CLOSED_MARKER = "（已结束）"

package io.element.android.libraries.pushproviders.huawei

import android.content.Context
import com.huawei.agconnect.config.AGConnectServicesConfig
import com.huawei.hms.aaid.HmsInstanceId
import com.huawei.hms.aaid.plugin.ProxyCenter
import com.huawei.hms.push.HmsMessaging
import dev.zacsweers.metro.AppScope
import dev.zacsweers.metro.ContributesBinding
import dev.zacsweers.metro.Inject
import dev.zacsweers.metro.SingleIn
import dev.zacsweers.metro.binding
import io.element.android.libraries.di.annotations.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

fun interface HuaweiPushTokenSource {
    suspend fun getToken(): Result<String>
}

@ContributesBinding(AppScope::class, binding = binding<HuaweiPushTokenSource>())
@SingleIn(AppScope::class)
@Inject
class DefaultHuaweiPushTokenSource(
    @ApplicationContext private val context: Context,
    private val diagnostics: HuaweiPushDiagnostics,
) : HuaweiPushTokenSource {
    override suspend fun getToken(): Result<String> = runCatching {
        withContext(Dispatchers.IO) {
            val servicesConfig = AGConnectServicesConfig.fromContext(context)
            val appId = servicesConfig.getString("client/app_id")
                ?.takeIf(String::isNotBlank)
                ?: context.getString(R.string.huawei_push_app_id).takeIf(String::isNotBlank)
                ?: throw HuaweiPushAppIdUnavailableException()
            val projectId = servicesConfig.getString("client/project_id")
                ?.takeIf(String::isNotBlank)
                ?: context.getString(R.string.huawei_push_project_id).takeIf(String::isNotBlank)
                ?: throw HuaweiPushProjectIdUnavailableException()

            // HMS Push 6.13 re-reads these values from AGConnectServicesConfig when it builds
            // TokenReq. HarmonyOS' Android compatibility runtime cannot always decrypt the
            // resources generated by the AGConnect Gradle plugin, so overlay the same public
            // variant identifiers before entering the SDK.
            servicesConfig.setParam("client/app_id", appId)
            servicesConfig.setParam("app_info/app_id", appId)
            servicesConfig.setParam("client/project_id", projectId)
            diagnostics.recordStage("TOKEN_REQUESTING")
            val token = HmsInstanceId.getInstance(context)
                .getToken(appId, HmsMessaging.DEFAULT_TOKEN_SCOPE)
            token?.takeIf(String::isNotBlank)
                ?: if (ProxyCenter.getProxy() != null) {
                    throw HuaweiPushTokenPendingException()
                } else {
                    throw HuaweiPushTokenUnavailableException()
                }
        }
    }
}

class HuaweiPushAppIdUnavailableException : IllegalStateException("Huawei App ID is unavailable")
class HuaweiPushProjectIdUnavailableException : IllegalStateException("Huawei project ID is unavailable")
class HuaweiPushTokenPendingException : IllegalStateException("Huawei Push token is pending asynchronously")
class HuaweiPushTokenUnavailableException : IllegalStateException("Huawei Push token is unavailable")
